namespace ktsu.ImGui.Phosphor;

/// <summary>
/// The phosphor a monochrome cathode ray tube was coated with, which decides the one hue every
/// element on the screen is drawn in.
/// </summary>
public enum PhosphorTint
{
	/// <summary>P1 green phosphor: the classic green-on-black terminal.</summary>
	Green,

	/// <summary>P3 amber phosphor: the warm orange-on-black terminal.</summary>
	Amber,
}
